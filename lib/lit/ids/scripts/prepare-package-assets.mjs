/**
 * Prepare publishable assets for `@ids/core`:
 * 1. Bundle + minify IDS theme CSS (light/dark + fallbacks) into styles/
 * 2. Copy repo icons into package assets/icons/
 *
 * Run from package root via `npm run build:assets`.
 */
import {
  cpSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  writeFileSync,
} from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const pkgRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const repoRoot = resolve(pkgRoot, "../../..");

const themeSrc = join(repoRoot, "components/ids-theme.css");
const fallbacksSrc = join(repoRoot, "components/ids-theme-fallbacks.css");
const iconsSrc = join(repoRoot, "assets/icons");
const stylesDir = join(pkgRoot, "styles");
const assetsIconsDir = join(pkgRoot, "assets/icons");

function minifyCss(css) {
  return css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/\s+/g, " ")
    .replace(/\s*([{}:;,])\s*/g, "$1")
    .replace(/;}/g, "}")
    .trim();
}

function prepareTheme() {
  if (!existsSync(themeSrc) || !existsSync(fallbacksSrc)) {
    throw new Error(
      `Missing theme sources. Expected:\n  ${themeSrc}\n  ${fallbacksSrc}`,
    );
  }

  const banner = [
    "/* @ids/core — IDS theme tokens (light + dark).",
    " * Generated by scripts/prepare-package-assets.mjs — do not edit.",
    " * Switch at runtime via applyIdsTheme({ theme: 'light' | 'dark' | … }).",
    " */",
    "",
  ].join("\n");

  const bundled =
    banner +
    readFileSync(themeSrc, "utf8").trim() +
    "\n\n" +
    "/* --- IDS theme fallbacks / completion layer --- */\n" +
    readFileSync(fallbacksSrc, "utf8").trim() +
    "\n";

  mkdirSync(stylesDir, { recursive: true });
  writeFileSync(join(stylesDir, "ids-theme.css"), bundled, "utf8");
  writeFileSync(join(stylesDir, "ids-theme.min.css"), minifyCss(bundled) + "\n", "utf8");
  console.log("[prepare-package-assets] wrote styles/ids-theme.css (+ .min.css)");
}

function prepareIcons() {
  if (!existsSync(iconsSrc)) {
    throw new Error(`Missing icons source: ${iconsSrc}`);
  }
  rmSync(assetsIconsDir, { recursive: true, force: true });
  mkdirSync(join(pkgRoot, "assets"), { recursive: true });
  cpSync(iconsSrc, assetsIconsDir, { recursive: true });
  console.log("[prepare-package-assets] copied assets/icons/");
}

prepareTheme();
prepareIcons();
