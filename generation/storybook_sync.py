from __future__ import annotations

import hashlib
import json
import re
from pathlib import Path
from typing import Any, Dict, Iterable


def _slug_to_pascal(slug: str) -> str:
    return "".join(part.capitalize() for part in re.split(r"[^a-zA-Z0-9]+", slug) if part)


def compute_spec_layer_hash(context: Dict[str, Any]) -> str:
    payload = {
        "spec_layers": context.get("spec_layers", []),
        "theme_layers": context.get("theme_layers", []),
        "layer_precedence": context.get("layer_precedence", ""),
    }
    blob = json.dumps(payload, sort_keys=True, ensure_ascii=True)
    return hashlib.sha256(blob.encode("utf-8")).hexdigest()


def story_header(component_slug: str, spec_hash: str) -> str:
    return "\n".join(
        [
            "/* @generated by strict-spec-storybook-gate */",
            f"/* component: {component_slug} */",
            f"/* spec_hash: {spec_hash} */",
            "",
        ]
    )


def extract_existing_spec_hash(path: Path) -> str:
    if not path.exists():
        return ""
    text = path.read_text(encoding="utf-8", errors="ignore")
    match = re.search(r"/\*\s*spec_hash:\s*([a-f0-9]{64})\s*\*/", text)
    return match.group(1) if match else ""


def ensure_under_generated_root(path: Path, generated_root: Path) -> None:
    resolved_path = path.resolve()
    resolved_root = generated_root.resolve()
    if resolved_root not in resolved_path.parents and resolved_path != resolved_root:
        raise ValueError(f"Refusing to write outside generated storybook root: {path}")


def ensure_react_import_for_jsx(storybook_code: str) -> str:
    """Spec-generated stories live outside storybook/tsconfig `include`; ensure React is in scope for JSX."""
    text = storybook_code or ""
    if not re.search(r"<\s*[A-Za-z/]", text):
        return text
    if re.search(r"\bimport\s+React\b", text):
        return text
    lines = text.splitlines(keepends=True)
    for i, line in enumerate(lines):
        if line.lstrip().startswith("import "):
            lines.insert(i, 'import React from "react";\n')
            return "".join(lines)
    return 'import React from "react";\n' + text


def get_story_path(
    *,
    component_slug: str,
    generated_root: Path,
    subdir: str = "src/components",
    framework: str = "react",
) -> Path:
    extension = ".stories.ts" if framework.lower() == "angular" else ".stories.tsx"
    story_filename = f"{_slug_to_pascal(component_slug)}{extension}"
    return generated_root / subdir / story_filename


# Angular pilot components: story CSF co-located with implementation (storybook-angular only).
ANGULAR_COLOCATED_STORY_REL: dict[str, str] = {
    "accordion": "src/components/ids-accordion/ids-accordion.stories.js",
    "alert": "src/components/ids-alert/ids-alert.stories.js",
    "badge": "src/components/ids-badge/ids-badge.stories.js",
    "button": "src/components/ids-button/ids-button.stories.js",
    "main-menu-left": "src/components/ids-main-menu-left/ids-main-menu-left.stories.js",
    "text-box": "src/components/ids-text-box/ids-text-box.stories.js",
}


def get_angular_colocated_story_path(angular_package_root: Path, component_slug: str) -> Path | None:
    rel = ANGULAR_COLOCATED_STORY_REL.get(component_slug.lower())
    if not rel:
        return None
    return angular_package_root / rel


def write_generated_story(
    *,
    component_slug: str,
    storybook_code: str,
    generated_root: Path,
    subdir: str = "src/components",
    framework: str = "react",
    angular_package_root: Path | None = None,
) -> Path:
    if not storybook_code.strip():
        raise ValueError(f"Empty STORYBOOK output for component: {component_slug}")

    if framework.lower() != "angular":
        storybook_code = ensure_react_import_for_jsx(storybook_code)

    colocated = (
        get_angular_colocated_story_path(angular_package_root, component_slug)
        if framework.lower() == "angular" and angular_package_root is not None
        else None
    )
    if colocated is not None:
        output_path = colocated
    else:
        output_path = get_story_path(
            component_slug=component_slug,
            generated_root=generated_root,
            subdir=subdir,
            framework=framework,
        )
        ensure_under_generated_root(output_path, generated_root)

    output_path.parent.mkdir(parents=True, exist_ok=True)
    output_path.write_text(storybook_code, encoding="utf-8")
    return output_path


def prepend_generated_header(storybook_code: str, header: str) -> str:
    if storybook_code.startswith("/* @generated by strict-spec-storybook-gate */"):
        return storybook_code
    return f"{header}{storybook_code.lstrip()}"


def ensure_storybook_theme_import(storybook_code: str, design_system_slug: str) -> str:
    """
  Spec Generated stories must import exactly one program theme file.
  IDS → components/ids-theme.css; DAP → components/dap-theme.css.
  """
    from generation.deterministic_storybook.helpers import (
        THEME_CSS_BY_DESIGN_SYSTEM,
        storybook_theme_import_line,
    )

    canonical = storybook_theme_import_line(design_system_slug)
    text = storybook_code or ""

    for path in THEME_CSS_BY_DESIGN_SYSTEM.values():
        legacy = f'import "../../../../{path}";'
        if legacy != canonical:
            text = text.replace(legacy + "\n", "")
    text = re.sub(
        r'import "\.\./\.\./\.\./\.\./components/theme\.css";\n?',
        "",
        text,
    )

    if canonical in text:
        return text

    lines = text.splitlines(keepends=True)
    insert_at = 0
    for i, line in enumerate(lines):
        if line.lstrip().startswith("import "):
            insert_at = i
            break
    else:
        for i, line in enumerate(lines):
            stripped = line.strip()
            if stripped and not stripped.startswith("/*"):
                insert_at = i
                break
    lines.insert(insert_at, canonical + "\n")
    return "".join(lines)


def idempotent_drift(before: str, after: str) -> bool:
    return before != after


def list_story_files(root: Path, *, framework: str = "react") -> Iterable[Path]:
    if not root.exists():
        return []
    pattern = "*.stories.ts" if framework.lower() == "angular" else "*.stories.tsx"
    return root.rglob(pattern)
